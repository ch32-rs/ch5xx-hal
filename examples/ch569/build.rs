use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    // `USER_MEM` (InfoFlash [31:30]) splits the 128K window at 0x20020000 into
    // RAMX and the zero-wait ROM code area: 32/64/96K of RAMX. This EVT board
    // is 64K; a 96K board can leave the default and just loses the upper 32K.
    println!("cargo:rerun-if-env-changed=CH569_USER_MEM");
    let ramx_kb: u32 = std::env::var("CH569_USER_MEM")
        .ok()
        .and_then(|v| v.trim().trim_end_matches(['k', 'K']).parse().ok())
        .unwrap_or(64);
    assert!(
        matches!(ramx_kb, 32 | 64 | 96),
        "CH569_USER_MEM must be 32, 64 or 96 (got {ramx_kb})"
    );

    let rom_base = 0x2002_0000 + ramx_kb * 1024;
    let rom_kb = 128 - ramx_kb;
    let mut memory_x = String::new();
    writeln!(
        memory_x,
        "/* Generated by build.rs from CH569_USER_MEM={ramx_kb}. RAMX/ROM are a\n\
         * per-part option in InfoFlash; writing past RAMX is silently dropped. */"
    )
    .unwrap();
    memory_x.push_str("MEMORY\n{\n");
    writeln!(memory_x, "    CODEFLASH (rwx) : ORIGIN = 0x00000000, LENGTH =  448K").unwrap();
    writeln!(memory_x, "    DATAFLASH (rwx) : ORIGIN = 0x00070000, LENGTH =   32K").unwrap();
    writeln!(memory_x, "    RAMS      (rwx) : ORIGIN = 0x20000000, LENGTH =   16K").unwrap();
    writeln!(
        memory_x,
        "    RAMX      (rwx) : ORIGIN = 0x20020000, LENGTH = {ramx_kb:>4}K"
    )
    .unwrap();
    // Zero-wait code area; only the on-chip loader knows how to fill it.
    writeln!(
        memory_x,
        "    ROM       (rx)  : ORIGIN = 0x{rom_base:08X}, LENGTH = {rom_kb:>4}K"
    )
    .unwrap();
    memory_x.push_str("}\n\n");
    memory_x.push_str("REGION_ALIAS(\"FLASH\", CODEFLASH);\n\n");
    memory_x.push_str("REGION_ALIAS(\"RAM\", RAMS);\n");
    memory_x.push_str("REGION_ALIAS(\"REGION_TEXT\", CODEFLASH);\n");
    memory_x.push_str("REGION_ALIAS(\"REGION_RODATA\", CODEFLASH);\n");
    memory_x.push_str("REGION_ALIAS(\"REGION_DATA\", RAMS);\n");
    memory_x.push_str("REGION_ALIAS(\"REGION_BSS\", RAMS);\n");
    memory_x.push_str("REGION_ALIAS(\"REGION_HEAP\", RAMS);\n");
    memory_x.push_str("REGION_ALIAS(\"REGION_STACK\", RAMS);\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out.join("memory.x"), memory_x).unwrap();

    // The board's RAMX/ROM split lives in the generated `memory.x`, so the
    // linker has to see OUT_DIR before the HAL's generated one.
    println!("cargo:rustc-link-search={}", out.display());
    // Order matters. `link.x` places orphan sections at `ORIGIN(FLASH)`, so
    // `defmt.x` — which assigns `.defmt` to a range past the vector table —
    // must be processed *after* it. Passing `-Tdefmt.x` via `rustflags` puts it
    // first and silently lands `.defmt` at 0x0, on top of the vector table.
    println!("cargo:rustc-link-arg-bins=-Tlink.x");
    println!("cargo:rustc-link-arg-bins=-Tdefmt.x");
}
